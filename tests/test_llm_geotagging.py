"""Tests for pipeline.llm_geotagging's Groq request construction.

Run from the repo root with:  python -m pytest tests/ -q

Context: openai/gpt-oss-20b is a reasoning model. Its default
reasoning_effort ("medium", per Groq's docs and the groq-python SDK's own
docstring) burns a variable, often large, number of hidden chain-of-thought
tokens before it ever starts on the actual JSON answer. With this call's
max_tokens=200 budget, that CoT was eating the whole budget on 64% of real
calls in production, so finish_reason came back "length" with no JSON ever
generated (Groq error json_validate_failed: "max completion tokens reached
before generating a valid document").

Per console.groq.com/docs/reasoning (verified 2026-10-13):
  - reasoning_effort="low"|"medium"|"high" is the ONLY parameter that
    changes how many reasoning tokens gpt-oss-20b actually generates
    ("low: a small number of reasoning tokens" vs "medium: a moderate
    number" vs "high: a large number"). This is the fix for the token
    starvation itself.
  - include_reasoning=False (gpt-oss's reasoning-visibility control; it
    does NOT support the separate reasoning_format parameter at all) only
    removes the reasoning text from the HTTP response payload. The docs
    state plainly that hidden/excluded reasoning is still generated by the
    model ("The model will still reason, but the reasoning content will
    not be returned in the response") -- i.e. it does NOT give back any of
    the token budget. It is set here only to keep the response payload
    small/clean, never as the fix for truncation.

These tests stub the Groq client (no real network access / API key is used
or required) and assert on the exact kwargs passed to
client.chat.completions.create, plus that the existing parsing/validation
path is untouched.
"""

import json
from types import SimpleNamespace
from unittest.mock import MagicMock, patch

from pipeline import llm_geotagging


class _StubGroqClient:
    """Records the kwargs of the last chat.completions.create() call and
    returns a canned response built from `content`."""

    def __init__(self, content: str):
        self.last_kwargs = None
        self._content = content
        self.chat = SimpleNamespace(
            completions=SimpleNamespace(create=self._create)
        )

    def _create(self, **kwargs):
        self.last_kwargs = kwargs
        message = SimpleNamespace(content=self._content)
        choice = SimpleNamespace(message=message)
        return SimpleNamespace(choices=[choice])


def _patched(stub_client, cached=None):
    """Context-manager-free helper: patches the cache functions so no real
    DB is needed, and returns the patch objects (use as a `with` target)."""
    return patch.multiple(
        llm_geotagging,
        get_cached_llm_result=MagicMock(return_value=cached),
        set_cached_llm_result=MagicMock(),
    )


def test_request_includes_low_reasoning_effort_and_hides_reasoning():
    """The exact fix under test: reasoning_effort="low" + include_reasoning=False
    must be present in the request payload sent to Groq."""
    stub = _StubGroqClient(json.dumps({"action": "accept", "confidence": 0.9}))
    client_info = {"provider": "groq", "client": stub}

    with _patched(stub):
        result = llm_geotagging.resolve_entity_with_llm(
            client_info, "Prospect Park", "GPE", "chilling in prospect park rn", conn=object()
        )

    assert stub.last_kwargs is not None, "client.chat.completions.create was never called"
    assert stub.last_kwargs["model"] == llm_geotagging.GROQ_MODEL_NAME
    assert stub.last_kwargs["reasoning_effort"] == "low"
    assert stub.last_kwargs["include_reasoning"] is False
    # Untouched by this fix:
    assert stub.last_kwargs["response_format"] == {"type": "json_object"}
    assert stub.last_kwargs["temperature"] == 0
    assert stub.last_kwargs["max_tokens"] == 200
    assert stub.last_kwargs["timeout"] == 10
    # reasoning_format must NOT be set: gpt-oss-20b does not support it at
    # all (docs: "the reasoning_format parameter is not supported"), and it
    # is mutually exclusive with include_reasoning in the groq-python SDK.
    assert "reasoning_format" not in stub.last_kwargs

    assert result == {
        "action": "accept",
        "lat": None,
        "lng": None,
        "query": None,
        "confidence": 0.9,
    }


def test_parsing_and_validation_path_unchanged_for_resolve_action():
    stub = _StubGroqClient(
        json.dumps({"action": "resolve", "lat": 40.7, "lng": -73.9, "confidence": 0.8})
    )
    client_info = {"provider": "groq", "client": stub}

    with _patched(stub):
        result = llm_geotagging.resolve_entity_with_llm(
            client_info, "Prospect Park", "GPE", "chilling in prospect park rn", conn=object()
        )

    assert result == {
        "action": "resolve",
        "lat": 40.7,
        "lng": -73.9,
        "query": None,
        "confidence": 0.8,
    }


def test_invalid_json_still_fails_safe_to_none():
    """If the model still truncates (e.g. reasoning_effort="low" reduces but
    does not guarantee zero CoT tokens), the call must keep degrading to
    None rather than raising, exactly as before this change."""
    stub = _StubGroqClient("{not valid json")
    client_info = {"provider": "groq", "client": stub}

    with _patched(stub):
        result = llm_geotagging.resolve_entity_with_llm(
            client_info, "Prospect Park", "GPE", "chilling in prospect park rn", conn=object()
        )

    assert result is None


class _StubClaudeClient:
    """Records the kwargs of the last messages.create() call and the
    timeout passed to with_options(), and returns a canned response in
    Claude's response.content == [block with .type/.text] shape."""

    def __init__(self, content: str):
        self.last_kwargs = None
        self.last_timeout = None
        self._content = content
        self.messages = SimpleNamespace(create=self._create)

    def with_options(self, timeout=None):
        self.last_timeout = timeout
        return self

    def _create(self, **kwargs):
        self.last_kwargs = kwargs
        block = SimpleNamespace(type="text", text=self._content)
        return SimpleNamespace(content=[block])


def test_claude_request_shape_and_no_sampling_params():
    """Claude path, mirroring the Groq request-shape test above. Also pins
    down a real bug caught via a live smoke-test call against the actual
    Anthropic endpoint: the installed anthropic SDK's messages.create() no
    longer accepts `temperature` at all (TypeError, not a 400 from the
    server) -- confirmed by inspecting the live method signature after the
    first version of this code raised on it. This test guards against that
    regressing back in."""
    stub = _StubClaudeClient(json.dumps({"action": "accept", "confidence": 0.9}))
    client_info = {"provider": "claude", "client": stub}

    with _patched(stub):
        result = llm_geotagging.resolve_entity_with_llm(
            client_info, "Prospect Park", "GPE", "chilling in prospect park rn", conn=object()
        )

    assert stub.last_kwargs is not None, "messages.create was never called"
    assert stub.last_kwargs["model"] == llm_geotagging.CLAUDE_MODEL_NAME
    assert stub.last_kwargs["max_tokens"] == 256
    assert stub.last_kwargs["system"] == llm_geotagging.SYSTEM_PROMPT
    assert stub.last_kwargs["messages"] == [{"role": "user", "content": stub.last_kwargs["messages"][0]["content"]}]
    assert "temperature" not in stub.last_kwargs
    assert "top_p" not in stub.last_kwargs
    assert "top_k" not in stub.last_kwargs
    assert stub.last_timeout == 10.0

    assert result == {
        "action": "accept",
        "lat": None,
        "lng": None,
        "query": None,
        "confidence": 0.9,
    }


